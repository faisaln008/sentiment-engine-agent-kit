/**
 * Prompt-iteration comparison from COMMITTED evidence (S8a): separates prompt quality from deadline/heuristic noise.
 *   npx tsx apps/backend/eval/llm-only.ts --run '<name>|<eval label>|<sanitised server log>' (×N) [--out <name.md>]
 * For each run: metrics on all tune chunks, on chunks the LLM answered (log provider ∉ {heuristic, none}), and on the
 * intersection of chunks the LLM answered in EVERY run (same items, so differences are the prompt, not timeouts).
 * Single run of each prompt at temperature 0; per-chunk run-to-run variance is not measured — read Δ < ~0.03 as noise.
 */
import { parseArgs } from 'node:util';
import { SENTIMENTS } from '@app/contracts';
import { loadSplit, type LabelledChunk } from './lib/dataset.js';
import { computeMetrics } from './lib/eval-metrics.js';
import type { ChunkResult } from './lib/eval-run.js';
import { readRaw } from './lib/raw-store.js';
import { num, pct, table, writeReport } from './lib/reports.js';
import { readServerLog } from './lib/server-log.js';

const { values: a } = parseArgs({
  options: {
    run: { type: 'string', multiple: true, default: [] },
    out: { type: 'string', default: 'prompt-iterations-s8a.md' },
  },
});

interface Run {
  name: string;
  label: string;
  log: string;
  results: ChunkResult[];
  llm: Set<string>;
}

const rows = loadSplit('tune').rows;
const isLlm = (p: string | undefined): boolean => !!p && p !== 'heuristic' && p !== 'none';

function load(spec: string): Run {
  const [name, label, log] = spec.split('|');
  if (!name || !label || !log) throw new Error(`bad --run ${spec}`);
  const store = readRaw(label);
  if (!store) throw new Error(`no raw store for ${label}`);
  const server = readServerLog(log);
  if (!server) throw new Error(`server log ${log} missing`);
  const prov = new Map<string, string>();
  for (const [k, v] of server.byChunk) {
    const [sid, cid] = k.split('\u0000');
    if (sid?.includes('~') && cid) prov.set(cid, v.provider);
  }
  const results = rows.map((r) => {
    const x = store.results.get(r.chunk_id);
    if (!x) throw new Error(`${label} lacks ${r.chunk_id}`);
    return x;
  });
  const llm = new Set(rows.filter((r) => isLlm(prov.get(r.chunk_id))).map((r) => r.chunk_id));
  return { name, label, log, results, llm };
}

const runs = (a.run ?? []).map(load);
if (runs.length === 0) throw new Error('pass at least one --run');
const common = rows.filter((r) => runs.every((x) => x.llm.has(r.chunk_id)));
const scope = (sel: LabelledChunk[], r: Run): ReturnType<typeof computeMetrics> =>
  computeMetrics(sel, r.results);
const cell = (m: ReturnType<typeof computeMetrics>): string =>
  `${num(m.cls.macroF1)} · ${pct(m.cls.strict)} / ${pct(m.cls.lenient)} (n ${m.n})`;

const summary = table(
  [
    'run (eval label)',
    'all chunks: macro-F1 · strict / lenient',
    'LLM-answered',
    `LLM-answered in every run`,
  ],
  runs.map((r) => [
    `${r.name} (\`${r.label}\`)`,
    cell(scope(rows, r)),
    cell(
      scope(
        rows.filter((x) => r.llm.has(x.chunk_id)),
        r,
      ),
    ),
    cell(scope(common, r)),
  ]),
);
const perClass = table(
  ['class (common set)', ...runs.map((r) => r.name)],
  SENTIMENTS.map((s) => [
    s,
    ...runs.map((r) => {
      const c = scope(common, r).cls.perClass.find((p) => p.label === s);
      return c ? `${num(c.f1)} (n ${c.support})` : '—';
    }),
  ]),
);
const invocation = `npx tsx apps/backend/eval/llm-only.ts ${process.argv
  .slice(2)
  .map((s) => `'${s}'`)
  .join(' ')}`;
const md = [
  '# Prompt iterations S8a — LLM-only comparison (tune split)',
  '',
  `Generated by \`${invocation}\` from committed \`reports/raw/eval-<label>.jsonl\` + sanitised server logs.`,
  `Common set = ${common.length} of ${rows.length} tune chunks answered by the LLM in every run (deadline timeouts excluded).`,
  'One run per prompt at temperature 0; run-to-run variance not measured, so treat |Δ macro-F1| < ~0.03 as noise.',
  '',
  summary,
  '',
  perClass,
  '',
].join('\n');
writeReport(a.out, md);
console.log(md);
